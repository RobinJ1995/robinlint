const AD_ERROR = 'Commit messages and PR descriptions should not contain tool-injected advertising';

const TOOLS = ['claude', 'claude code', 'codex', 'chatgpt', 'openai', 'copilot', 'github copilot', 'cursor', 'gemini', 'antigravity', 'junie'];

const AD_RULES = [
    text => /^(🤖 Generated with \[Claude Code\]\(https:\/\/claude\.com\/claude-code\)|_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code(\/session_\w+)?\)_)$/m.test(text),
    text => /^https:\/\/claude\.ai\/code\/session_\w+$/m.test(text),
    text => /^Claude-Session: https:\/\/claude\.ai\/code\/session_\w+$/m.test(text),
    text => /^\[Codex Task\]\(https:\/\/chatgpt\.com\/codex\/(cloud\/)?tasks\/task_\w+\)$/m.test(text),
    text => /^<!-- (START|END) COPILOT CODING AGENT (TIPS|SUFFIX) -->$/m.test(text),
    text => text.split('\n').some(line => TOOLS.some(tool => [`generated with ${tool}`, `generated by ${tool}`].includes(line.toLowerCase()))),
    text => /^Co-authored-by: .+ <(noreply@anthropic\.com|noreply@openai\.com|codex@openai\.com|cursoragent@cursor\.com)>$/im.test(text)
];

const adsInText = (rule, where, text) => {
    if (!AD_RULES.some(isAd => isAd(text ?? ''))) {
        return [];
    }

    return [{
        rule,
        file: null,
        line: null,
        output: `${where}: error: ${AD_ERROR}`,
        isError: true
    }];
};

const adsInPRBody = pullRequest => {
    if (pullRequest === null) {
        return [];
    }

    const { title, body } = pullRequest.event.pull_request;

    return [
        ...adsInText('no-ads-in-prs', 'PR title', title),
        ...adsInText('no-ads-in-prs', 'PR description', body)
    ];
};

module.exports = { adsInPRBody };
