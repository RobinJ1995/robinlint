const { test } = require('node:test');
const Assert = require('node:assert/strict');
const { isPRAd, isCommitAd } = require('../ads');

test('Claude Code footers', () => {
    Assert.ok(isPRAd('🤖 Generated with [Claude Code](https://claude.com/claude-code)'));
    Assert.ok(isPRAd('🤖 Generated with [Claude Code](https://claude.ai/code)'));
    Assert.ok(isPRAd('🤖 Generated with Claude Code'));
    Assert.ok(isPRAd('Generated with [Claude Code](https://claude.ai/code)'));
    Assert.ok(isPRAd('_Generated by [Claude Code](https://claude.ai/code)_'));
    Assert.ok(isPRAd('_Generated by [Claude Code](https://claude.ai/code/session_01AbCdEfGhIjKlMnOpQrStUv)_'));
});

test('Claude Code session links', () => {
    Assert.ok(isPRAd('https://claude.ai/code/session_01AbCdEfGhIjKlMnOpQrStUv'));
    Assert.ok(isPRAd('Claude-Session: https://claude.ai/code/session_01AbCdEfGhIjKlMnOpQrStUv'));
});

test('Codex task links', () => {
    Assert.ok(isPRAd('https://chatgpt.com/codex/tasks/task_e_0123456789abcdef0123456789abcdef'));
    Assert.ok(isPRAd('[Codex Task](https://chatgpt.com/codex/cloud/tasks/task_e_0123456789abcdef0123456789abcdef)'));
});

test('Copilot coding agent markers', () => {
    Assert.ok(isPRAd('<!-- START COPILOT CODING AGENT TIPS -->'));
    Assert.ok(isPRAd('<!-- START COPILOT CODING AGENT SUFFIX -->'));
    Assert.ok(isPRAd('<!-- START COPILOT ORIGINAL PROMPT -->'));
});

test('Cursor attribution', () => {
    Assert.ok(isPRAd('Made-with: Cursor'));
    Assert.ok(isPRAd('Made with [Cursor](https://cursor.com)'));
    Assert.ok(isPRAd('<!-- CURSOR_AGENT_PR_BODY_BEGIN -->'));
    Assert.ok(isPRAd('<!-- CURSOR_SUMMARY -->'));
});

test('Jules, Devin and Amp attribution', () => {
    Assert.ok(isPRAd('*PR created automatically by Jules for task [1234567890](https://jules.google.com/task/1234567890) started by @someone*'));
    Assert.ok(isPRAd('Link to Devin session: https://app.devin.ai/sessions/0123456789abcdef0123456789abcdef'));
    Assert.ok(isPRAd('Amp-Thread-ID: https://ampcode.com/threads/T-01234567-89ab-cdef-0123-456789abcdef'));
});

test('tools as co-authors', () => {
    Assert.ok(isPRAd('Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'));
    Assert.ok(isPRAd('Co-authored-by: Codex <noreply@openai.com>'));
    Assert.ok(isPRAd('Co-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>'));
    Assert.ok(isPRAd('Co-authored-by: Cursor Agent <cursoragent@cursor.com>'));
    Assert.ok(isPRAd('Co-authored-by: Junie <junie@jetbrains.com>'));
    Assert.ok(isPRAd('Co-authored-by: Gemini <noreply@google.com>'));
});

test('people mentioning the tools are not ads', () => {
    Assert.ok(!isPRAd('A Claude Code on the web container has Docker installed (Codex P2 on #34).'));
    Assert.ok(!isPRAd('Claude session to re-audit the diff against this section.'));
    Assert.ok(!isPRAd('see https://claude.ai/code/session_01AbCdEfGhIjKlMnOpQrStUv for details'));
    Assert.ok(!isPRAd('Built by a Codex Cloud task: https://chatgpt.com/codex/tasks/task_e_0123456789abcdef0123456789abcdef'));
    Assert.ok(!isPRAd('Each play now records `source_session_id`, on top of `claude/stripe-1-schema`.'));
    Assert.ok(!isPRAd('Co-authored-by: Alice <alice@example.com>'));
});

test('commit message ads', () => {
    Assert.ok(isCommitAd('🤖 Generated with [Claude Code](https://claude.com/claude-code)'));
    Assert.ok(isCommitAd('https://claude.ai/code/session_01AbCdEfGhIjKlMnOpQrStUv'));
    Assert.ok(isCommitAd('Made-with: Cursor'));
    Assert.ok(isCommitAd('Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'));
});

test('commit message metadata trailers are not ads', () => {
    Assert.ok(!isCommitAd('Claude-Session: https://claude.ai/code/session_01AbCdEfGhIjKlMnOpQrStUv'));
    Assert.ok(!isCommitAd('Amp-Thread-ID: https://ampcode.com/threads/T-01234567-89ab-cdef-0123-456789abcdef'));
});
